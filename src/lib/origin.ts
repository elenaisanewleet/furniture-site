/**
 * Свой домен или временный.
 * -------------------------------------------------------------------------
 * Пока сайт живёт на бесплатном адресе Vercel, его нельзя пускать в поиск.
 * Причина не в аккуратности, а в том, что это трудно откатить: Яндекс и
 * Google проиндексируют сорок две страницы на `что-то.vercel.app`, а через
 * месяц появится настоящий домен — и в выдаче окажутся два одинаковых
 * сайта. Старые адреса будут висеть месяцами, растаскивая на себя ссылки и
 * позиции, которые должны были достаться новому домену.
 *
 * Поэтому временный адрес закрыт от индексации целиком: noindex на каждой
 * странице и Disallow в robots.txt. Как только появится свой домен и
 * SITE_URL укажет на него, обе заглушки снимутся сами — править ничего не
 * нужно.
 */

/** Хосты, которые не являются собственным доменом мастерской. */
const TEMPORARY = [
  /\.vercel\.app$/, // бесплатный адрес Vercel
  /\.netlify\.app$/,
  /\.pages\.dev$/,
  /(^|\.)example\.(ru|com|org)$/, // заглушка из astro.config
  /^localhost$/,
  /\.local$/,
  /^\d+\.\d+\.\d+\.\d+$/, // голый IP — тоже не домен для поиска
];

export function isTemporaryOrigin(site: URL | undefined): boolean {
  // Адрес неизвестен — значит точно не боевой.
  if (!site) return true;
  return TEMPORARY.some((re) => re.test(site.hostname));
}
