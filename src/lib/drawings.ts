/**
 * Чертежи вместо фотографий.
 * -------------------------------------------------------------------------
 * Настоящих снимков мастерской на сайте нет и не будет, пока мастер их не
 * согласует. Пустая рамка с подписью «фотография не загружена» — честно, но
 * смотреть на неё нечего, а таких мест на сайте шестьдесят два.
 *
 * Поэтому каждое место под фотографию получает рисунок: линейный чертёж того,
 * что там будет снято. Это не заглушка «на время» — это язык сайта. Мастерская
 * работает по чертежу, и сайт разговаривает так же: контур, размерная линия,
 * выноска, номер листа.
 *
 * Мотивы нарисованы вручную в системе координат 320×220. Компонент Drawing
 * вписывает их в рамку любых пропорций и добавляет обвязку: сетку, размеры,
 * подпись. Слот выбирает мотив по имени — см. pickMotif().
 *
 * Классы штриха:
 *   s — конструктив, толстая линия        a — аннотация, акцентный цвет
 *   d — детализация, тонкая линия         g — невидимый контур, пунктир
 *   h — заливка штриховкой                c — осевая линия
 */

export interface Motif {
  /** Что изображено — уходит в подпись под рамкой. */
  title: string;
  /** Разметка внутри <svg viewBox="0 0 320 220">. */
  body: string;
}

/* ----------------------------------------------------------- примитивы ---- */

/* pathLength="1" приводит все контуры к одной «длине»: линия в 8 единиц и
   контур в 900 прочерчиваются одинаково, без замера длин в рантайме. */
const PL = 'pathLength="1"';

const R = (x: number, y: number, w: number, h: number, cls = 's', rx = 0) =>
  `<rect x="${x}" y="${y}" width="${w}" height="${h}"${rx ? ` rx="${rx}"` : ''} ${PL} class="dw-${cls}"/>`;

const L = (x1: number, y1: number, x2: number, y2: number, cls = 'd') =>
  `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" ${PL} class="dw-${cls}"/>`;

const C = (cx: number, cy: number, r: number, cls = 'd') =>
  `<circle cx="${cx}" cy="${cy}" r="${r}" ${PL} class="dw-${cls}"/>`;

const P = (d: string, cls = 'd') => `<path d="${d}" ${PL} class="dw-${cls}"/>`;

/** Размерная линия со стрелками и подписью. */
const DIM = (x1: number, y1: number, x2: number, y2: number, label: string) => {
  const mx = (x1 + x2) / 2;
  const my = (y1 + y2) / 2;
  const vertical = Math.abs(x2 - x1) < Math.abs(y2 - y1);
  return (
    `<g class="dw-dim">` +
    L(x1, y1, x2, y2, 'a') +
    `<path d="M${x1} ${y1} l${vertical ? '-3 6' : '6 -3'} ${vertical ? 'l6 0' : 'l0 6'} z" class="dw-tip"/>` +
    `<path d="M${x2} ${y2} l${vertical ? '-3 -6' : '-6 -3'} ${vertical ? 'l6 0' : 'l0 6'} z" class="dw-tip"/>` +
    `<text x="${vertical ? mx - 5 : mx}" y="${vertical ? my : my - 5}" class="dw-txt"${
      vertical ? ` transform="rotate(-90 ${mx - 5} ${my})"` : ''
    }>${label}</text>` +
    `</g>`
  );
};

/** Выноска: кружок на детали, полка с номером. */
const CALL = (x: number, y: number, tx: number, ty: number, n: string) =>
  `<g class="dw-call">` +
  C(x, y, 3.2, 'a-fill') +
  L(x, y, tx, ty, 'a') +
  L(tx, ty, tx + (tx > x ? 16 : -16), ty, 'a') +
  `<text x="${tx + (tx > x ? 8 : -8)}" y="${ty - 4}" text-anchor="middle" class="dw-txt">${n}</text>` +
  `</g>`;

