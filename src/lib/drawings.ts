/** Подбирает мотив по имени слота. Незнакомое имя получает общий вид шкафа. */
export function pickMotif(slot: string): Motif {
  const key = slot.toLowerCase();
  for (const [re, name] of ROUTES) if (re.test(key)) return MOTIFS[name];
  return MOTIFS.wardrobe;
}

/** Номер листа — стабилен для слота, чтобы рисунок не «прыгал» между сборками. */
export function sheetCode(slot: string): string {
  let h = 0;
  for (const ch of slot) h = (h * 31 + ch.charCodeAt(0)) % 997;
  return String(h % 90 + 10).padStart(2, '0');
}

